namespace Ifgf\ChurchOperations\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\HasMany;

class Branch extends Model
{
    use HasFactory;

    protected $table = 'ifgf_branches';

    protected $fillable = ['code', 'name', 'name_zh', 'timezone', 'gmaps_url', 'sort_order', 'is_active'];

    protected function casts(): array
    {
        return ['is_active' => 'boolean', 'sort_order' => 'integer'];
    }

    public function members(): HasMany
    {
        return $this->hasMany(Member::class, 'branch_id');
    }

    public function occurrences(): HasMany
    {
        return $this->hasMany(ServiceOccurrence::class, 'branch_id');
    }

    public function scopeActive($q)
    {
        return $q->where('is_active', true);
    }
}
